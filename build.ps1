#   前の [^)]+ は最初の ) で切れて、リンク先を取り違え、残りの名前が本文に生で残っていた。
#   <...> の形と、1 段の対の括弧を受ける。%xx はほどいてから許可リストと比べる。
$linkDest = '(?<u><[^>\n]*>|(?:[^()\n]|\([^()\n]*\))+)'
$heldRe = [regex]('「?\[(?<t>[^\]]+)\]\(' + $linkDest + '\)」?')
